"""Prompt templates for triage, static analysis, and verification.

A single combined analysis prompt covers all three categories (security / logic /
quality) per code segment — one LLM call instead of three, which matters a lot with a
large reasoning model.
"""
from __future__ import annotations

from app.models.findings import Finding, Triage

# --------------------------------------------------------------------------- #
# Triage
# --------------------------------------------------------------------------- #
TRIAGE_SYSTEM = """\
You are a senior engineer triaging an unfamiliar, possibly AI-generated ("vibe-coded") \
codebase. From the file map and key manifest/config files, infer what the app is, its \
frameworks, how it is meant to run, which areas most likely hide bugs or vulnerabilities, \
and which specific files most deserve a deep security/correctness review.

Output ONLY a JSON object of this shape:
{"app_type":"<e.g. React SPA, Express API, Flask app>","frameworks":["..."],\
"how_to_run":"<build/start commands if evident>","risk_areas":["<short labels>"],\
"priority_files":["<relative/path>","..."],"notes":"<anything notable>"}

List priority_files using the exact relative paths from the file map, most important \
first. No markdown, no text outside the JSON."""


def build_triage_messages(map_text: str, manifests_text: str) -> list[dict]:
    user = f"File map:\n{map_text}\n\nKey files:\n{manifests_text}\n\nReturn the triage JSON."
    return [
        {"role": "system", "content": TRIAGE_SYSTEM},
        {"role": "user", "content": user},
    ]


# --------------------------------------------------------------------------- #
# Static analysis (combined 3-category pass)
# --------------------------------------------------------------------------- #
ANALYSIS_SYSTEM = """\
You are a world-class code auditor reviewing code generated by an AI coding assistant \
("vibe-coded"). Such code frequently ships with hardcoded secrets, missing auth, injection \
sinks, broken error handling, incorrect async, and half-finished logic. Find REAL, \
defensible bugs — not style nits.

Review the code across three categories:
- security: hardcoded secrets/API keys, missing authentication/authorization, SQL/NoSQL/\
command injection, XSS, SSRF, path traversal, insecure deserialization, insecure CORS, \
missing input validation, sensitive data exposure, weak crypto, dangerous defaults \
(debug mode on, wildcard CORS, disabled TLS verification).
- logic: null/undefined/None access, unhandled exceptions and promise rejections, missing \
or incorrect await, off-by-one/boundary errors, race conditions, wrong conditionals, state \
mutation bugs, resource leaks, missing error handling, placeholder/stub/TODO logic that \
silently no-ops.
- quality: misuse of libraries/APIs, type inconsistencies, data-loss risks, dead/unreachable \
code, duplicated logic that will drift, performance footguns (N+1 queries, blocking I/O on \
an event loop, unbounded loops/memory).

Rules:
- Only report issues you can justify from the code shown. Prefer PRECISION over recall. Do \
NOT invent problems or speculate about code you cannot see.
- Use the exact line numbers shown in the numbered code (format "N| code").
- Report at most 12 findings, most important first.
- Output ONLY a JSON object, no markdown, no commentary."""

OUTPUT_CONTRACT = """\
JSON shape:
{"findings":[{"category":"security|logic|quality","title":"<short specific title>",\
"severity":"critical|high|medium|low|info","line_start":<int>,"line_end":<int>,\
"description":"<what is wrong and why>","impact":"<concrete consequence / failure scenario>",\
"recommendation":"<specific fix>","confidence":<0.0-1.0>,"cwe":"<CWE-id or null>"}]}
If nothing is wrong, return {"findings":[]}."""


def build_analysis_messages(
    numbered_code: str,
    path: str,
    start: int,
    end: int,
    is_chunk: bool,
    triage: Triage | None,
    want_profile: bool = False,
) -> list[dict]:
    app_type = (triage.app_type if triage else "") or "unknown"
    frameworks = ", ".join(triage.frameworks) if triage and triage.frameworks else "unknown"
    chunk_note = " [partial chunk of a larger file]" if is_chunk else ""
    user = (
        f"Project: {app_type} | frameworks: {frameworks}\n"
        f"File: {path} (showing lines {start}-{end}){chunk_note}\n\n"
        f"Numbered code:\n{numbered_code}\n\n"
        f"Audit this code and return the JSON."
    )
    contract = OUTPUT_CONTRACT + ("\n\n" + PROFILE_CONTRACT if want_profile else "")
    return [
        {"role": "system", "content": ANALYSIS_SYSTEM + "\n\n" + contract},
        {"role": "user", "content": user},
    ]


# Used instead of a separate triage call when auditing a single snippet.
PROFILE_CONTRACT = """\
Also add a top-level "profile" key describing the code itself:
"profile":{"app_type":"<what this code is, e.g. Express API, React component, Python CLI>",\
"frameworks":["<libraries/frameworks used>"]}"""


# --------------------------------------------------------------------------- #
# Verification (Phase 3 — false-positive filtering)
# --------------------------------------------------------------------------- #
VERIFY_SYSTEM = """\
You verify whether a reported code issue is a TRUE POSITIVE. Given the finding and the \
actual code, decide if it is real, reachable, and correctly described. Be skeptical of \
false positives from automated reviewers.

Output ONLY JSON: {"verdict":"confirmed|plausible|dropped","confidence":<0.0-1.0>,\
"reason":"<one sentence>"}."""


VERIFY_BATCH_SYSTEM = """\
You verify whether reported code issues are TRUE POSITIVES. For EACH numbered finding, decide \
from the actual code whether it is real, reachable, and correctly described. Be skeptical of \
false positives from automated reviewers, but do not drop real issues.

Output ONLY JSON: {"verdicts":[{"id":<finding number>,"verdict":"confirmed|plausible|dropped",\
"confidence":<0.0-1.0>,"reason":"<one sentence>"}]} with one entry per finding."""


def build_verify_batch_messages(findings: list[Finding], path: str, numbered_code: str) -> list[dict]:
    """One call that checks every finding in a file (instead of one call per finding)."""
    items = "\n".join(
        f"{i}. [{f.severity.value} {f.category.value}] lines {f.line_start}-{f.line_end}: "
        f"{f.title} — {f.description}"
        for i, f in enumerate(findings, start=1)
    )
    user = (
        f"File: {path}\n\nReported issues:\n{items}\n\n"
        f"Actual code:\n{numbered_code}\n\nReturn the verdicts JSON."
    )
    return [
        {"role": "system", "content": VERIFY_BATCH_SYSTEM},
        {"role": "user", "content": user},
    ]


def build_verify_messages(finding: Finding, numbered_code: str) -> list[dict]:
    user = (
        f"Reported issue:\n"
        f"- title: {finding.title}\n"
        f"- category: {finding.category.value} | severity: {finding.severity.value}\n"
        f"- file: {finding.file} lines {finding.line_start}-{finding.line_end}\n"
        f"- description: {finding.description}\n\n"
        f"Actual code:\n{numbered_code}\n\n"
        f"Return the verdict JSON."
    )
    return [
        {"role": "system", "content": VERIFY_SYSTEM},
        {"role": "user", "content": user},
    ]
